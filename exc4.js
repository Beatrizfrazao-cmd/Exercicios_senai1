//Peça o preço original de um produto e a porcentagem de desconto. Calcule e mostre o preço final após o desconto.
let preco = Number(prompt("Adicione o preço do produto"))
let desconto = 0.85
const resultado = (preco * desconto)
//
document.write("<br>O preço do seu produto é: ")
document.write("<br>O desconto é de: 15%")
document.write("<br>O valor á pagar é de: " + resultado + " R$" )